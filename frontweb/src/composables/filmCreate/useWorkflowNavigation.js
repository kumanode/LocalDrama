import { useNavigation } from './useNavigation'
import { useActiveTasks } from './useActiveTasks'
import { useStepNavigation } from './useStepNavigation'

export function useWorkflowNavigation({
  dramaId,
  genStore,
  pipelineRunning,
  pipelinePaused,
  pipelineAbortRequested,
  pipelineCurrentStep,
  storyGenerating,
  scriptGenerating,
  universalOmniPolishRunning,
  universalOmniPolishProgress,
  universalOmniPolishAbort,
  batchImageRunning,
  batchImageStopping,
  batchVideoRunning,
  batchVideoStopping,
  batchVideoProgress,
  currentEpisodeId,
  scriptContent,
  characters,
  charactersGenerating,
  generatingCharIds,
  hasAssetImage,
  props,
  propsExtracting,
  generatingPropIds,
  scenes,
  scenesExtracting,
  generatingSceneIds,
  storyboards,
  storyboardGenerating,
  hasSbImage,
  generatingSbImageIds,
  getSbAllVideos,
  generatingSbVideoIds,
}) {
  const navigation = useNavigation()

  const activeTasks = useActiveTasks({
    dramaId,
    genStore,
    pipelineRunning,
    pipelinePaused,
    pipelineAbortRequested,
    pipelineCurrentStep,
    storyGenerating,
    scriptGenerating,
    universalOmniPolishRunning,
    universalOmniPolishProgress,
    universalOmniPolishAbort,
    batchImageRunning,
    batchImageStopping,
    batchVideoRunning,
    batchVideoStopping,
    batchVideoProgress,
  })

  const stepNavigation = useStepNavigation({
    genStore,
    dramaId,
    currentEpisodeId,
    scriptContent,
    isStoryGenRunning: activeTasks.isStoryGenRunning,
    characters,
    charactersGenerating,
    generatingCharIds,
    hasAssetImage,
    props,
    propsExtracting,
    generatingPropIds,
    scenes,
    scenesExtracting,
    generatingSceneIds,
    storyboards,
    storyboardGenerating,
    universalOmniPolishRunning,
    hasSbImage,
    generatingSbImageIds,
    batchImageRunning,
    getSbAllVideos,
    generatingSbVideoIds,
    batchVideoRunning,
  })

  return {
    ...navigation,
    ...activeTasks,
    ...stepNavigation,
  }
}
