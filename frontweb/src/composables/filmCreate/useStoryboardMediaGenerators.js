import { useStoryboardImages } from './useStoryboardImages'
import { useStoryboardVideo } from './useStoryboardVideo'
import { useBatchGeneration } from './useBatchGeneration'

export function useStoryboardMediaGenerators({
  store,
  dramaId,
  currentEpisodeId,
  storyboardUseFirstLastFrame,
  lastFrameUseFirstLayoutLock,
  gridMode,
  generatingSbFirstImageIds,
  generatingSbLastImageIds,
  generatingSbImageIds,
  upscalingSbIds,
  linkingTailFrameIds,
  usingPrevTailAsFirstIds,
  sbCharacterIds,
  sbSelectedImgId,
  sbSelectedLastImgId,
  ensureProfessionalFramePrompt,
  buildLastFrameImagePrompt,
  getSbFirstImage,
  getSbLastImage,
  getSbImage,
  getSbVideo,
  getNextStoryboard,
  getPrevStoryboard,
  getSelectedStyle,
  projectAspectRatio,
  assetImageUrl,
  frameTypeForSlot,
  buildSbGenMeta,
  pollTask,
  loadDrama,
  loadSingleStoryboardMedia,
  refreshStoryboardsOnly,
  restoreSelectionsFromBackend,
  onSelectSbFrameImage,
  genStore,
  videoResolution,
  getSbVideoDurationForApi,
  isSbUniversalMode,
  sbUniversalSegmentTrimmed,
  getSbFirstFrameUrl,
  getSbLastFrameUrl,
  isSbVideoGenerating,
  getSbResumableFailedVideo,
  sbVideoErrors,
  sbSelectedVideoId,
  generatingSbVideoIds,
  getSbSelectedScene,
  getSbSelectedCharacters,
  getSbSelectedProps,
  hasAssetImage,
  pipelineRunning,
  pipelineConcurrency,
  pipelineVideoConcurrency,
  batchImageRunning,
  batchImageStopping,
  batchImageProgress,
  batchImageErrors,
  batchVideoRunning,
  batchVideoStopping,
  batchVideoProgress,
  batchVideoErrors,
  videoFrameContiguity,
  sbImages,
  sbVideos,
  hasSbImage,
  loadStoryboardMedia,
  recordHasPlayableVideoUrl,
}) {
  const images = useStoryboardImages({
    store,
    dramaId,
    storyboardUseFirstLastFrame,
    lastFrameUseFirstLayoutLock,
    gridMode,
    generatingSbFirstImageIds,
    generatingSbLastImageIds,
    generatingSbImageIds,
    upscalingSbIds,
    linkingTailFrameIds,
    usingPrevTailAsFirstIds,
    sbCharacterIds,
    sbSelectedImgId,
    sbSelectedLastImgId,
    ensureProfessionalFramePrompt,
    buildLastFrameImagePrompt,
    getSbFirstImage,
    getSbLastImage,
    getSbImage,
    getSbVideo,
    getNextStoryboard,
    getPrevStoryboard,
    getSelectedStyle,
    projectAspectRatio,
    assetImageUrl,
    frameTypeForSlot,
    buildSbGenMeta,
    pollTask,
    loadDrama,
    loadSingleStoryboardMedia,
    refreshStoryboardsOnly,
    restoreSelectionsFromBackend,
    onSelectSbFrameImage,
    genStore,
  })

  const video = useStoryboardVideo({
    store,
    dramaId,
    videoResolution,
    projectAspectRatio,
    getSelectedStyle,
    getSbVideoDurationForApi,
    isSbUniversalMode,
    sbUniversalSegmentTrimmed,
    storyboardUseFirstLastFrame,
    getSbFirstFrameUrl,
    getSbLastFrameUrl,
    isSbVideoGenerating,
    getSbResumableFailedVideo,
    sbVideoErrors,
    sbSelectedVideoId,
    generatingSbVideoIds,
    getSbSelectedScene,
    getSbSelectedCharacters,
    getSbSelectedProps,
    hasAssetImage,
    assetImageUrl,
    buildSbGenMeta,
    pollTask,
    loadSingleStoryboardMedia,
    genStore,
  })

  const batch = useBatchGeneration({
    store,
    dramaId,
    currentEpisodeId,
    pipelineRunning,
    pipelineConcurrency,
    pipelineVideoConcurrency,
    batchImageRunning,
    batchImageStopping,
    batchImageProgress,
    batchImageErrors,
    batchVideoRunning,
    batchVideoStopping,
    batchVideoProgress,
    batchVideoErrors,
    videoFrameContiguity,
    sbImages,
    sbVideos,
    hasSbImage,
    storyboardUseFirstLastFrame,
    isSbUniversalMode,
    gridMode,
    ensureProfessionalFramePrompt,
    getSelectedStyle,
    projectAspectRatio,
    videoResolution,
    pollTask,
    loadStoryboardMedia,
    loadSingleStoryboardMedia,
    sbSelectedImgId,
    sbSelectedVideoId,
    restoreSelectionsFromBackend,
    recordHasPlayableVideoUrl,
    sbCanSubmitVideo: video.sbCanSubmitVideo,
    collectSbOmniReferenceAbsoluteUrls: video.collectSbOmniReferenceAbsoluteUrls,
    getSbFirstFrameUrl,
    generatingSbVideoIds,
    getMainImageUrlForVideo: video.getMainImageUrlForVideo,
    toAbsoluteImageUrl: video.toAbsoluteImageUrl,
    sbVideoFirstLastUrls: video.sbVideoFirstLastUrls,
    buildSbVideoPromptForApi: video.buildSbVideoPromptForApi,
    getSbVideoDurationForApi,
    buildSbGenMeta,
  })

  return {
    ...images,
    ...video,
    ...batch,
  }
}
