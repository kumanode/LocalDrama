  try {
    pipelineCurrentStep.value = t('filmCreate.pipeLoadingData')
    await loadDrama()

    // 1. 角色：没有则生成角色；再为每个无图角色生成图
    let chars = store.currentEpisode?.characters ?? []
    if (chars.length === 0) {
      await checkPause()
      pipelineCurrentStep.value = t('filmCreate.pipeGenCharList')
