function isErrorCode(str) {
  return typeof str === 'string' && /^[A-Z0-9_]{3,}$/.test(str);
}

function getErrorMessage(code, lang = 'zh') {
  const dict = lang === 'en' ? errorsEn : errorsZh;
  return dict[code] || errorsZh[code] || errorsEn[code] || code;
}

